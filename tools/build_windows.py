"""Build the single-file Windows executable of SparkBox: dist/SparkBox-<version>-windows-x64.exe.

Steps: write packaging/version_info.txt from app.branding.VERSION; build the application folder with PyInstaller
(packaging/sparkbox.spec); copy the license files of every bundled third-party package into it
(LICENSES/third-party, with INVENTORY.txt of exact versions); zip it; compile packaging/SparkBoxLauncher.cs with the .NET Framework C# compiler that
ships with Windows, embedding the zip, a build id and the banner logo. The result needs no Python on the user's
computer. See packaging/README.md for what the launcher does at run time.

Usage (Windows, from the project folder, in an environment with requirements-build.txt and gregorithm installed):
  python tools/build_windows.py                   full build
  python tools/build_windows.py --launcher-only   recompile only the launcher around the last payload

Limits: Windows x64 only. The build uses whatever versions are installed in the current environment; record them
for a release. The executable is not code-signed, so Windows SmartScreen may warn on first run.
"""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / ".cache"
VERSION_INFO = """# Generated by tools/build_windows.py: Windows file properties of SparkBox.exe.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
                    subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Alessandro Gregucci'),
      StringStruct('FileDescription', 'SparkBox - battery data analysis'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('InternalName', 'SparkBox'),
      StringStruct('LegalCopyright', 'Copyright (c) 2026 Alessandro Gregucci. MIT License.'),
      StringStruct('OriginalFilename', 'SparkBox.exe'),
      StringStruct('ProductName', 'SparkBox'),
      StringStruct('ProductVersion', '{version}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version() -> str:
    """The application version declared in app/branding.py."""
    text = (ROOT / "app" / "branding.py").read_text(encoding="utf-8")
    match = re.search(r'^VERSION = "([0-9]+\.[0-9]+\.[0-9]+)"', text, re.MULTILINE)
    if not match:
        raise SystemExit("VERSION not found in app/branding.py")
    return match.group(1)


def zip_folder(folder: Path, target: Path) -> None:
    """Zip ``folder`` (with its own name as the top directory) in a stable file order."""
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in sorted(folder.rglob("*")):
            arcname = Path(folder.name) / path.relative_to(folder)
            if path.is_dir():
                archive.writestr(arcname.as_posix() + "/", "")
            else:
                archive.write(path, arcname.as_posix())


def logo(target: Path) -> None:
    """256 px banner logo made from the 1024 px application icon."""
    from PySide6.QtCore import Qt
    from PySide6.QtGui import QImage
    image = QImage(str(ROOT / "assets" / "icon" / "sparkbox.png"))
    image.scaled(256, 256, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation) \
        .save(str(target), "PNG")


# Distributions whose code ends up in the executable (import name -> distribution name). Their license and notice
# files are copied unchanged into the bundle; build-only tools are left out, except PyInstaller, whose bootloader
# runs the application.
BUNDLED = ("PySide6_Essentials", "shiboken6", "pyqtgraph", "numpy", "pyarrow", "scipy", "gregorithm", "pyinstaller")
LICENSE_WORDS = ("license", "licence", "copying", "notice", "copyright", "authors")
# Repository license texts used when a Qt for Python wheel ships none (Linux and macOS wheels).
QT_LICENSE_FALLBACK = {name: ("LGPL-3.0.txt", "GPL-3.0.txt") for name in ("PySide6_Essentials", "shiboken6")}


def third_party_licenses(target: Path) -> list[str]:
    """Copy the license / notice files of the BUNDLED distributions and of Python into ``target`` (one folder per
    distribution) and write INVENTORY.txt with name, version and license metadata. Returns the inventory lines.
    Raises SystemExit when a bundled distribution is missing or ships no license file: a release must never go out
    without them."""
    from importlib import metadata
    target.mkdir(parents=True, exist_ok=True)
    lines = [f"Python {sys.version.split()[0]} - PSF License (Python-LICENSE.txt)"]
    base = Path(sys.base_prefix)
    major_minor = f"python{sys.version_info.major}.{sys.version_info.minor}"
    candidates = (base / "LICENSE.txt", base / "lib" / major_minor / "LICENSE.txt")   # Windows, macOS / Linux
    python_license = next((c for c in candidates if c.is_file()), None)
    if python_license is None:
        raise SystemExit("Python license file (LICENSE.txt) not found")
    shutil.copyfile(python_license, target / "Python-LICENSE.txt")
    for name in BUNDLED:
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            raise SystemExit(f"Bundled package not installed: {name}") from None
        files = [f for f in dist.files or () if any(w in f.name.lower() for w in LICENSE_WORDS)
                 and ".dist-info" in str(f)]
        folder = target / f"{dist.metadata['Name']}-{dist.version}"
        if not files and name in QT_LICENSE_FALLBACK:
            # The Linux and macOS wheels of Qt for Python ship no license file (the Windows ones do); Qt is bundled
            # under the LGPL-3.0, whose texts (LGPL-3.0 builds on GPL-3.0) are kept in the repository.
            folder.mkdir(parents=True, exist_ok=True)
            for text in QT_LICENSE_FALLBACK[name]:
                shutil.copyfile(ROOT / "LICENSES" / text, folder / text)
        elif not files:
            raise SystemExit(f"No license file found for {name}")
        for f in files:
            inside = Path(*[part for part in Path(str(f)).parts if not part.endswith(".dist-info")])
            destination = folder / inside
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(Path(dist.locate_file(f)), destination)
        licence = dist.metadata.get("License-Expression") or dist.metadata.get("License") or ""
        if not licence or "\n" in licence.strip() or len(licence) > 100:      # a whole license text, not a name
            licence = "see the license files in its folder"
        lines.append(f"{dist.metadata['Name']} {dist.version} - {licence}")
    header = ["Third-party packages bundled in this SparkBox executable (generated by tools/build_windows.py).",
              "Their license and notice files are in the folders next to this file; see also THIRD_PARTY_NOTICES.md.",
              ""]
    (target / "INVENTORY.txt").write_text(os.linesep.join(header + lines) + os.linesep, encoding="utf-8")
    return lines


def build_folder(folder_dist: Path) -> None:
    """PyInstaller build of the application folder into ``folder_dist/SparkBox``."""
    print("1/3 PyInstaller: application folder", flush=True)
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
                    "--distpath", str(folder_dist), "--workpath", str(CACHE / "pyinstaller-work"),
                    str(ROOT / "packaging" / "sparkbox.spec")], cwd=ROOT, check=True)


def main() -> int:
    """Run every build step; returns 0 and prints the path of the executable."""
    if os.name != "nt":
        raise SystemExit("Build the Windows executable on Windows.")
    compiler = Path(os.environ["SYSTEMROOT"]) / "Microsoft.NET" / "Framework64" / "v4.0.30319" / "csc.exe"
    if not compiler.is_file():
        raise SystemExit("The .NET Framework C# compiler (csc.exe) was not found.")
    ver = version()
    nums = tuple(int(n) for n in ver.split(".")) + (0,)
    (ROOT / "packaging" / "version_info.txt").write_text(VERSION_INFO.format(nums=nums, version=ver),
                                                         encoding="utf-8")
    CACHE.mkdir(exist_ok=True)
    dist = ROOT / "dist"
    folder_dist = CACHE / "pyinstaller-dist"
    launcher_only = "--launcher-only" in sys.argv
    payload = CACHE / "payload.zip"
    if launcher_only and not payload.is_file():
        raise SystemExit("No earlier payload: run a full build first.")
    if not launcher_only:
        build_folder(folder_dist)
        for line in third_party_licenses(folder_dist / "SparkBox" / "_internal" / "LICENSES" / "third-party"):
            print("   license:", line, flush=True)
        print("2/3 Payload zip", flush=True)
        zip_folder(folder_dist / "SparkBox", payload)
    digest = hashlib.sha256(payload.read_bytes()).hexdigest()[:16]
    build_id = CACHE / "build_id.txt"
    build_id.write_text(f"{ver}-{digest}", encoding="ascii")
    banner_logo = CACHE / "sparkbox-logo.png"
    logo(banner_logo)
    print("3/3 Launcher", flush=True)
    dist.mkdir(exist_ok=True)
    exe = dist / f"SparkBox-{ver}-windows-x64.exe"
    subprocess.run([str(compiler), "/nologo", "/target:winexe", "/platform:x64", "/optimize+",
                    "/reference:System.Windows.Forms.dll", "/reference:System.Drawing.dll",
                    "/reference:System.IO.Compression.dll", "/reference:System.Core.dll",
                    f"/resource:{payload},sparkbox_payload", f"/resource:{build_id},sparkbox_build_id",
                    f"/resource:{banner_logo},sparkbox_logo",
                    f"/win32icon:{ROOT / 'assets' / 'icon' / 'sparkbox.ico'}", f"/out:{exe}",
                    str(ROOT / "packaging" / "SparkBoxLauncher.cs")], cwd=ROOT, check=True)
    shutil.rmtree(CACHE / "pyinstaller-work", ignore_errors=True)
    print(f"Built {exe} ({exe.stat().st_size / 2**20:.0f} MB), build {ver}-{digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
